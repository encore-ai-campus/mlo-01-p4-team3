function escapeAttribute(value) {
  return String(value ?? '').replace(/[&<>"']/g, character => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[character]);
}

/** Render a decorative local SVG. Keep the accessible label on its button or link. */
export function icon(name, className = '') {
  if (typeof name !== 'string' || !Object.hasOwn(ICON_PATHS, name)) return '';
  const extra = className ? ` ${escapeAttribute(className)}` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" class="ui-icon${extra}">${ICON_PATHS[name]}</svg>`;
}
